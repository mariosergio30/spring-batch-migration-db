-- ── 1. migration_report ─────────────────────────────────────
-- Tracks every migration event:
--   RECORD_ERROR  – a single document that failed to insert
--   JOB_SUMMARY   – one row per job execution with totals
-- (from migration_report.sql, included here for completeness)

CREATE TABLE migration_report (
    migration_report_pk NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    mongo_legacy_id     VARCHAR2(50),
    order_id            VARCHAR2(50),
    type                VARCHAR2(30),
    result              VARCHAR2(30),   -- OK | ERROR | WARNING | SUCCESS
    description         VARCHAR2(4000),
    records             NUMBER(10),
    created_at          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT migration_report_pk PRIMARY KEY (migration_report_pk)
);

-- ── 2. orders ───────────────────────────────────────────────
-- Target table that receives migrated documents from MongoDB.
-- Adjust columns / types to match the real domain model.

CREATE TABLE orders (
    order_pk   NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    legacy_id  VARCHAR2(50)    NOT NULL,
    customer   VARCHAR2(200),
    amount     NUMBER(15,2),
    status     VARCHAR2(30),
    created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT orders_pk PRIMARY KEY (order_pk)
);

-- Recommended index to detect duplicates on re-run
CREATE UNIQUE INDEX orders_legacy_id_ux ON orders (legacy_id);
